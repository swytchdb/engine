package effectschema

import (
	"fmt"
	"go/format"
	"go/token"
	"slices"
	"strings"
)

func scalarType(name string) bool {
	switch name {
	case typeBool, typeUint8, typeUint32, typeInt64, typeFloat64, typeString, typeBytes:
		return true
	}

	return false
}

func runtimeScalar(name string) string {
	switch name {
	case typeInt64:
		return "Int64"
	case typeFloat64:
		return "Float64"
	case typeUint8:
		return "Uint8"
	case typeUint32:
		return "Uint32"
	}

	return exported(name)
}

func typeParam(d declaration, name string) bool {
	return slices.Contains(d.params, name)
}

func runtimeName(d declaration, name string) string {
	if typeParam(d, name) {
		return name
	}

	if scalarType(name) {
		return "*graph." + runtimeScalar(name)
	}

	return "*" + name
}

func typeExpr(d declaration, name string, args []string) string {
	if typeParam(d, name) {
		return "v.type" + name
	}

	if scalarType(name) {
		return "graph." + runtimeScalar(name) + "Type"
	}

	expr := name + "Type"

	if len(args) > 0 {
		var values []string
		for _, arg := range args {
			values = append(values, typeExpr(d, arg, nil))
		}

		expr += "(" + strings.Join(values, ",") + ")"
	}

	return expr
}

// Generate compiles schemas against the public runtime Value and Type protocol.
// Generic type parameters represent runtime implementations, not Go scalars.
func Generate(source []byte, packageName string) ([]byte, error) {
	if packageName == "_" || !token.IsIdentifier(packageName) {
		return nil, fmt.Errorf("invalid package name %q", packageName)
	}

	declarations, err := parse(source)
	if err != nil {
		return nil, err
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by effectgen; DO NOT EDIT.\n\npackage %s\n\n", packageName)
	b.WriteString("import (\n pb \"github.com/swytchdb/engine/cluster/proto\"\n \"github.com/swytchdb/engine/graph\"\n)\n\n")

	for _, d := range declarations {
		var constraints, arguments, factoryParams, factoryArgs []string
		for _, param := range d.params {
			constraints = append(constraints, param+" graph.Value")
			arguments = append(arguments, param)
			factoryParams = append(factoryParams, "type"+param+" graph.Type["+param+"]")
			factoryArgs = append(factoryArgs, "type"+param)
		}

		decl, use := "", ""
		if len(arguments) > 0 {
			decl = "[" + strings.Join(constraints, ",") + "]"
			use = "[" + strings.Join(arguments, ",") + "]"
		}

		typ := d.name + use
		fmt.Fprintf(&b, "// %s is a runtime composite. It works standalone and when composed.\n// Emission consumes the sharing values; do not copy or concurrently mutate it.\n", d.name)

		if len(d.params) > 0 {
			fmt.Fprintf(&b, "// Use New%s to supply the runtime types for generic fields.\n", d.name)
		}

		fmt.Fprintf(&b, "type %s%s struct { graph.Composite\n", d.name, decl)

		for _, param := range d.params {
			fmt.Fprintf(&b, "type%s graph.Type[%s]\n", param, param)
		}

		b.WriteString("}\n\n")

		if len(d.params) == 0 {
			fmt.Fprintf(&b, "var _ graph.Value = (*%s)(nil)\n\n", typ)
		}

		fmt.Fprintf(&b, "// New%s constructs an empty value without queuing effects.\nfunc New%s%s(%s) *%s { return &%s{", d.name, d.name, decl, strings.Join(factoryParams, ","), typ, typ)

		for _, param := range d.params {
			fmt.Fprintf(&b, "type%s:type%s,", param, param)
		}

		b.WriteString("} }\n\n")
		fmt.Fprintf(&b, "// %sType is the runtime type descriptor, usable without a schema at runtime.\n", d.name)

		if len(d.params) == 0 {
			fmt.Fprintf(&b, "var %sType = graph.Type[*%s]{New:New%s}\n\n", d.name, typ, d.name)
		} else {
			fmt.Fprintf(&b, "func %sType%s(%s) graph.Type[*%s] { return graph.Type[*%s]{New:func() *%s { return New%s(%s) }} }\n\n", d.name, decl, strings.Join(factoryParams, ","), typ, typ, typ, d.name, strings.Join(factoryArgs, ","))
		}

		extras := ""

		descriptor := d.name + "Type"
		if len(d.params) > 0 {
			extras = "," + strings.Join(factoryParams, ",")
			descriptor += "(" + strings.Join(factoryArgs, ",") + ")"
		}

		fmt.Fprintf(&b, "// %sFromSnap loads an immutable snapshot without emitting it as data.\nfunc %sFromSnap%s(snapshot *pb.ReducedEffect%s) (*%s,error) { return %s.FromSnapshot(snapshot) }\n\n", d.name, d.name, decl, extras, typ, descriptor)

		for _, f := range d.fields {
			getter := exported(f.name)
			if scalarType(f.typ) {
				rt := runtimeScalar(f.typ)

				goType := f.typ
				if goType == typeBytes {
					goType = "[]byte"
				}

				fmt.Fprintf(&b, "// %sValue returns the standard runtime value for this field.\nfunc (v *%s) %sValue() *graph.%s { return graph.Bind(&v.Composite,%q,graph.%sType) }\n\n", getter, typ, getter, rt, f.name, rt)
				fmt.Fprintf(&b, "// %s materializes the current local value.\nfunc (v *%s) %s() %s { return v.%sValue().Value() }\n\n", getter, typ, getter, goType, getter)

				op := operation(f)
				fmt.Fprintf(&b, "// %s%s queues a %s operation and returns the same composite.\nfunc (v *%s) %s%s(value %s) *%s { v.%sValue().%s(value); return v }\n\n", op, getter, f.policy, typ, op, getter, goType, typ, getter, op)

				continue
			}

			var rt, desc string

			if f.element != "" {
				if f.typ == typeSet {
					rt = "*graph.StringSetField"
					desc = "graph.StringSetType"
				} else {
					gt := f.element
					if gt == typeBytes {
						gt = "[]byte"
					}

					rt = "*graph." + exported(f.typ) + "Field[" + gt + "]"
					desc = "graph." + exported(f.typ) + "Type(graph." + runtimeScalar(f.element) + "Codec)"
				}
			} else {
				rt = runtimeName(d, f.typ)
				if len(f.args) > 0 {
					var args []string
					for _, arg := range f.args {
						args = append(args, runtimeName(d, arg))
					}

					rt += "[" + strings.Join(args, ",") + "]"
				}

				desc = typeExpr(d, f.typ, f.args)
			}

			fmt.Fprintf(&b, "// %s returns the retained runtime value; edits participate in this composite.\nfunc (v *%s) %s() %s { return graph.Bind(&v.Composite,%q,%s) }\n\n", getter, typ, getter, rt, f.name, desc)
			fmt.Fprintf(&b, "// Set%s composes a standalone value, retaining its identity and pending edits.\nfunc (v *%s) Set%s(value %s) error { return v.Composite.Set(%q,value) }\n\n", getter, typ, getter, rt, f.name)
		}
	}

	return format.Source([]byte(b.String()))
}

// GenerateRuntime generates a library-owned type inside the runtime package,
// without importing that package into itself. Schema names are identifiers, so
// removing the generated qualifier cannot alter any user-provided field paths.
func GenerateRuntime(source []byte, packageName string) ([]byte, error) {
	code, err := Generate(source, packageName)
	if err != nil {
		return nil, err
	}

	local := strings.ReplaceAll(string(code), "\t\"github.com/swytchdb/engine/graph\"\n", "")
	local = strings.ReplaceAll(local, "graph.", "")

	return format.Source([]byte(local))
}
